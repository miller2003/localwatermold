// Writes 301s for county pages dropped by src/data/county-pages.json at the top of public/_redirects,
// between the markers. They must come first: Cloudflare counts static rules that follow a rule with a
// placeholder or splat as dynamic, and only 100 dynamic rules are allowed. Each goes to the first
// neighboring county that still has a page, else the state's county list. Run by build.mjs.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { stateSlug } from "../astro.config.mjs";

const BEGIN = "# BEGIN dropped county pages (generated by scripts/county-redirects.mjs)";
const END = "# END dropped county pages";
const rule = JSON.parse(readFileSync("src/data/county-pages.json", "utf8"));
const lines = [];
for (const st of readdirSync("src/data").filter((d) => existsSync(`src/data/${d}/counties.json`)).sort()) {
  const counties = JSON.parse(readFileSync(`src/data/${st}/counties.json`, "utf8")).counties;
  const keep = new Set(rule.keep[st] ?? []);
  const drop = new Set(rule.drop[st] ?? []);
  const hasPage = (c) => c.pilot && !drop.has(c.slug) && (c.population >= rule.minPopulation || keep.has(c.slug));
  const bySlug = new Map(counties.map((c) => [c.slug, c]));
  const base = `/${stateSlug(st)}/counties/`;
  for (const c of counties) {
    if (!c.pilot || hasPage(c)) continue;
    const near = c.adjacent.map((s) => bySlug.get(s)).find((n) => n && hasPage(n));
    lines.push(`${base}${c.slug}/ ${near ? `${base}${near.slug}/` : base} 301`);
  }
}
const file = "public/_redirects";
const text = readFileSync(file, "utf8");
const start = text.indexOf(BEGIN), stop = text.indexOf(END);
const rest = (start < 0 ? text : text.slice(0, start) + text.slice(stop + END.length)).trim();
writeFileSync(file, `${BEGIN}\n${lines.join("\n")}\n${END}\n\n${rest}\n`);
console.log(`County redirects: ${lines.length} dropped pages.`);
